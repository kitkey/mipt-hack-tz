from tzcheck.rules import _items, _locate


def test_items_split_ocr_bullets():
    assert _items("Референс: ТР 5006М ·Средство измерений (при отнесении к Си)") == ["Референс: ТР 5006М", "Средство измерений (при отнесении к Си)"]
    assert _items("• Микрометр — 2 шт. • Штангенциркуль — 5 шт.") == ["Микрометр — 2 шт.", "Штангенциркуль — 5 шт."]
    assert _items("Состав: 1) камера — 2 шт.; 2) маркеры") == ["Состав:", "камера — 2 шт.;", "маркеры"]


def test_items_keep_dash_inside_sentence():
    assert _items("Тип — испытательная камера. Диапазон 0-25 мм") == ["Тип — испытательная камера. Диапазон 0-25 мм"]


def test_locate_ignores_case_and_spaces():
    assert _locate("утверждённого типа (при отнесении к Си)", "при отнесении к СИ") == "при отнесении к Си"
    assert _locate("при  отнесении\nк СИ", "при отнесении к СИ") == "при  отнесении\nк СИ"
    assert _locate("Сила тока", "при отнесении к СИ") is None
