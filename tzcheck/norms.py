def norm_list_for_prompt() -> str:
    return "\n".join(f"{k}: {v['title']}. {v['text']}" for k, v in NORMS.items())


LAW_OF_NORM = {"223-FZ-": "223-ФЗ", "102-FZ-": "102-ФЗ", "GK-": "ГК ч.2"}


def apply_editions():
    for key, norm in NORMS.items():
        act = next((a for prefix, a in LAW_OF_NORM.items() if key.startswith(prefix)), None)
        rec = refdata.law_edition(act) if act else None
        cur = (rec or {}).get("current") or {}
        if cur.get("date"):
            norm["edition"] = f"действует с {cur['date']}, сверено с actual.pravo.gov.ru {refdata.msk(rec.get('checked_at'))}"


apply_editions()
